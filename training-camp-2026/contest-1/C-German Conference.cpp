using namespace std;

#define ll long long
#define ull unsigned long long
#define sz(x) (ll)(x).size()
#define rep(i, a, b) for (ll i=(a); i<(b); i++)

int main(){
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    ll n;
    cin>>n;

    ll ans=0;

    ll dg=to_string(n).size();
    ans+=max(dg-1, 1LL);

    for(ll i=1;i<=9;i++){
        ll x=0;
        while(1){
            ll next=10*x+i;
            if(next>n) break;
            x=next;
            ans++;
        }
    }
    cout<<ans;
    return 0;
}